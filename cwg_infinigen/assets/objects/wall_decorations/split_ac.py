"""Procedural high-wall split-system indoor AC head.

The factory follows the restrained residential design used by current inverter
heads: a slim satin-ABS monocoque, a separate lift-up fascia, a narrow recessed
discharge, a tucked motorized louvre, sparse direction vanes, a tiny status
cluster, and a subtle printed badge. Pipe trunking is generated by
``cable_trunk`` after placement so it can rise to the real room soffit instead
of being baked into an asset with no knowledge of the wall.
"""

import math

import bpy
from mathutils import Vector
from numpy.random import uniform

from cwg_infinigen.assets.objects.wall_decorations.primitives import (
    assign,
    box,
    brand_lettering,
    cylinder,
    disable_shadow_rays,
    plastic_material,
    rounded_box,
    shade_smooth,
    solid_material,
)
from cwg_infinigen.assets.utils.misc import generate_text
from cwg_infinigen.assets.utils.object import join_objects, new_bbox
from cwg_infinigen.core.placement.factory import AssetFactory
from cwg_infinigen.core.util import blender as butil
from cwg_infinigen.core.util.math import FixedSeed


class SplitACFactory(AssetFactory):
    """High-wall indoor unit: housing, open discharge, top intake, optional trunk."""

    def __init__(self, factory_seed, coarse=False):
        super().__init__(factory_seed, coarse=coarse)
        with FixedSeed(factory_seed):
            # Outer silhouette. The side wrap has to be a real radius, not a
            # 15 mm chamfer - that still reads as a flat end with a sharp
            # front-side crease. Clamp so two wraps cannot eat the depth.
            self.width = uniform(0.82, 1.08)
            self.height = uniform(0.285, 0.325)
            self.depth = uniform(0.205, 0.245)
            self.front_fillet = min(self.height, self.depth) * 0.145
            wrap = min(self.height, self.depth) * 0.30
            self.side_chamfer = min(wrap, self.depth * 0.40, self.height * 0.32)
            # How far the bottom front edge is drawn back relative to the top.
            self.front_taper = self.depth * uniform(0.12, 0.19)
            # Stand-off from the plaster. A high-wall head hangs on a steel
            # mounting plate, so the casing never touches the wall - there is a
            # 10-20 mm cavity behind it carrying the pipe run and the drain.
            #
            # Modelling it flush put the casing's back face at exactly 0.0000 m
            # from `<room>.wall` - measured on a generated bedroom - which is
            # two coincident surfaces, and Cycles resolves those per-ray. That
            # reads as the wall tearing through the unit.
            self.wall_gap = uniform(0.010, 0.018)
            # Vertical deflector vanes behind the discharge. These were
            # `n_coil_fins` at 32-44, which is an evaporator coil - and the coil
            # sits behind the *top* intake, not in the discharge. Packed into
            # the outlet at that pitch the front read as a radiator grille.
            # A real unit shows a handful of widely spaced vanes, mostly hidden
            # behind the louvre.
            self.n_vanes = int(uniform(8, 13))
            self.n_top_intake = int(uniform(8, 12))
            # Catalogue-style, partly open louvre: enough gap to expose the
            # throat without turning the flap into a projecting paddle.
            self.flap_open = uniform(math.radians(12), math.radians(26))
            # No side trunking. Reference photographs of installed high-wall
            # heads show the pipe run buried in the wall behind the unit or
            # dropped straight down behind it - the visible surface-mounted
            # duct read as an add-on and dominated the silhouette from the end.
            self.has_trunk = False
            self.trunk_side = 1.0 if uniform() < 0.5 else -1.0
            self.trunk_len = uniform(0.18, 0.40)
            self.trunk_h = uniform(0.10, 0.16)
            self.trunk_d = uniform(0.050, 0.070)
            self.trunk_rise = uniform(0.05, 0.09)
            # Leave highlight headroom. Near-one albedo clipped into a flat
            # white plane under the indoor exposure used by realism_v2.
            tone = uniform(0.72, 0.84)
            warm = uniform(0.008, 0.035)
            self.body_color = (tone, tone * (1.0 - warm * 0.35), tone * (1.0 - warm))
            self.grille_color = self.body_color
            self.trunk_color = self.body_color
            self.led_color = (0.12, 0.95, 0.28)
            btn = tone * uniform(0.72, 0.82)
            self.button_color = (btn, btn * 0.98, btn * 0.95)
            name = generate_text()[:8]
            if len(name) < 3:
                name = (name + generate_text())[:8]
            self.brand_name = name

    def _y_extent(self):
        extra = self.trunk_len if self.has_trunk else 0.0
        lo = -self.width / 2
        hi = self.width / 2
        if self.has_trunk:
            if self.trunk_side > 0:
                hi += extra
            else:
                lo -= extra
        return lo, hi

    def create_placeholder(self, **params):
        y0, y1 = self._y_extent()
        z_top = self.height / 2
        if self.has_trunk:
            z_top = max(
                z_top,
                -self.height * 0.08 + self.trunk_h / 2 + self.trunk_rise,
            )
        z_bot = -self.height / 2 - self.height * 0.08
        # Back of the box stays on the wall so the solver seats it flush; the
        # casing itself now starts `wall_gap` in front of that.
        return new_bbox(
            -0.002,
            self.depth + 0.08 + self.wall_gap,
            y0,
            y1,
            z_bot,
            z_top,
        )

    def _set_edge_weights(self, obj, predicate):
        mesh = obj.data
        attr = mesh.attributes.get("bevel_weight_edge")
        if attr is None:
            attr = mesh.attributes.new("bevel_weight_edge", "FLOAT", "EDGE")
        weights = []
        for edge in mesh.edges:
            v0 = Vector(mesh.vertices[edge.vertices[0]].co)
            v1 = Vector(mesh.vertices[edge.vertices[1]].co)
            weights.append(1.0 if predicate(v0, v1) else 0.0)
        attr.data.foreach_set("value", weights)

    def _shade_by_angle(self, obj, angle=0.40):
        """Smooth the fillets; keep the 90° slot rim sharp."""
        with butil.SelectObjects(obj):
            if hasattr(bpy.ops.object, "shade_smooth_by_angle"):
                bpy.ops.object.shade_smooth_by_angle(
                    angle=angle, keep_sharp_edges=True
                )
            else:
                shade_smooth(obj)

    def _clean_mesh(self, obj, dist=1.5e-4):
        """Weld bevel/boolean leftovers so the front is a single skin."""
        import bmesh

        bm = bmesh.new()
        bm.from_mesh(obj.data)
        bmesh.ops.remove_doubles(bm, verts=list(bm.verts), dist=dist)
        bmesh.ops.dissolve_degenerate(bm, dist=dist)
        bmesh.ops.recalc_face_normals(bm, faces=list(bm.faces))
        bm.to_mesh(obj.data)
        bm.free()
        obj.data.update()

    def _housing_d(self):
        return self.depth * 0.94

    def _front_x_at(self, z):
        """Analytic fascia X from the taper only. Prefer ``_fascia_x``."""
        z_min, z_max = -self.height / 2.0, self.height / 2.0
        span = max(z_max - z_min, 1e-6)
        t = max(0.0, (0.5 * (z_max + z_min) - z) / (0.5 * span))
        return self._housing_d() - self.front_taper * t * t

    def _fascia_x(self, housing, y, z):
        """Actual front-skin X at (y, z) after taper, wrap, and booleans.

        ``_front_x_at`` is the flat tapered plane. Side wraps pull the right
        and left fascia back, so a control cluster placed on that plane sits
        in the air in front of the curved end.
        """
        cache = getattr(self, "_fascia_cache", None)
        if cache is None or cache[0] is not housing:
            self._fascia_cache = (housing, {})
            cache = self._fascia_cache
        key = (round(float(y), 4), round(float(z), 4))
        if key in cache[1]:
            return cache[1][key]
        bpy.context.view_layer.update()
        origin = Vector((self._housing_d() + 0.28, y, z))
        hit, loc, _nrm, _idx = housing.ray_cast(origin, Vector((-1.0, 0.0, 0.0)))
        if hit:
            val = float(loc.x)
            cache[1][key] = val
            return val
        best_x, best_d = None, 1e9
        for v in housing.data.vertices:
            if v.co.x < self._housing_d() * 0.35:
                continue
            d = (v.co.y - y) ** 2 + (v.co.z - z) ** 2
            if d < best_d:
                best_d = d
                best_x = v.co.x
        val = float(best_x) if best_x is not None else self._front_x_at(z)
        cache[1][key] = val
        return val

    def _drape_front(self, obj, housing, offset=0.00012, thickness=0.00055):
        """Sit a front-facing patch on the real fascia, then give it thickness."""
        bpy.context.view_layer.update()
        for v in obj.data.vertices:
            v.co.x = self._fascia_x(housing, v.co.y, v.co.z) + offset
        obj.data.update()
        self._clean_mesh(obj, dist=1.0e-5)
        butil.modify_mesh(obj, "SOLIDIFY", thickness=thickness, offset=1.0)
        return obj

    def _front_patch(self, width, height, x, y, z, name, nw=8, nh=4):
        """Single-sided YZ grid facing +X, used as a drape source."""
        import bmesh

        mesh = bpy.data.meshes.new(name)
        obj = bpy.data.objects.new(name, mesh)
        bpy.context.scene.collection.objects.link(obj)
        bm = bmesh.new()
        verts = []
        for i in range(nw + 1):
            yy = y + (i / nw - 0.5) * width
            row = []
            for j in range(nh + 1):
                zz = z + (j / nh - 0.5) * height
                row.append(bm.verts.new((x, yy, zz)))
            verts.append(row)
        for i in range(nw):
            for j in range(nh):
                bm.faces.new((verts[i][j], verts[i + 1][j], verts[i + 1][j + 1], verts[i][j + 1]))
        bm.to_mesh(mesh)
        bm.free()
        mesh.update()
        return obj

    def _seat_text(self, obj, housing, offset=0.00008):
        """Keep letter thickness; put the back of the glyph on the fascia."""
        if not obj.data.vertices:
            return obj
        min_x = min(v.co.x for v in obj.data.vertices)
        for v in obj.data.vertices:
            fx = self._fascia_x(housing, v.co.y, v.co.z)
            v.co.x = fx + offset + max(0.0, v.co.x - min_x) * 0.45
        obj.data.update()
        return obj

    def _taper_front(self, obj):
        """Lean the lower front face back, so the body is a wedge not a brick.

        A high-wall head is deepest at the top, where the fan barrel and coil
        sit, and tapers toward the discharge along the bottom. A straight
        extruded box is the single clearest tell that this is a placeholder
        rather than an appliance.
        """
        verts = obj.data.vertices
        xs = [v.co.x for v in verts]
        zs = [v.co.z for v in verts]
        x_max, z_min, z_max = max(xs), min(zs), max(zs)
        span = max(z_max - z_min, 1e-6)
        for v in verts:
            if v.co.x < x_max - 1e-4:
                continue
            # 0 at mid-height, 1 at the very bottom; only the lower half moves.
            t = max(0.0, (0.5 * (z_max + z_min) - v.co.z) / (0.5 * span))
            v.co.x -= self.front_taper * t * t
        obj.data.update()

    def _shape_housing(self, obj):
        """Wrap the ends, then fillet the top/bottom rims.

        Must run on a solid (slot comes later). The front is tapered first, so
        the front-side column is a slant - selecting only axis-aligned edges
        left that crease sharp and the front-side-bottom corner a point.
        """
        def axes():
            xs = [v.co.x for v in obj.data.vertices]
            ys = [v.co.y for v in obj.data.vertices]
            zs = [v.co.z for v in obj.data.vertices]
            return min(xs), max(xs), min(ys), max(ys), min(zs), max(zs)

        x_min, x_max, y_min, y_max, z_min, z_max = axes()
        eps = 2.0e-3

        def on_side(p):
            return abs(p.y - y_min) < eps or abs(p.y - y_max) < eps

        def is_end_wrap(v0, v1):
            d = v1 - v0
            if abs(d.y) > max(abs(d.z), abs(d.x)) * 0.45:
                return False
            if abs(d.z) < self.height * 0.12:
                return False
            return on_side(v0) and on_side(v1)

        self._set_edge_weights(obj, is_end_wrap)
        butil.modify_mesh(
            obj,
            "BEVEL",
            width=self.side_chamfer,
            segments=8,
            limit_method="WEIGHT",
            use_clamp_overlap=True,
        )
        self._clean_mesh(obj)

        x_min, x_max, y_min, y_max, z_min, z_max = axes()

        def is_top_bottom_rim(v0, v1):
            d = v1 - v0
            mid = 0.5 * (v0 + v1)
            if abs(d.z) > max(abs(d.x), abs(d.y)):
                return False
            return abs(mid.z - z_min) < eps or abs(mid.z - z_max) < eps

        self._set_edge_weights(obj, is_top_bottom_rim)
        butil.modify_mesh(
            obj,
            "BEVEL",
            width=self.front_fillet,
            segments=6,
            limit_method="WEIGHT",
            use_clamp_overlap=True,
        )
        self._clean_mesh(obj)

    def _emissive(self, name, color, strength=18.0):
        mat = bpy.data.materials.new(name=name)
        mat.use_nodes = True
        nt = mat.node_tree
        bsdf = nt.nodes.get("Principled BSDF")
        rgba = (*color[:3], 1.0)
        bsdf.inputs["Base Color"].default_value = rgba
        bsdf.inputs["Roughness"].default_value = 0.18
        if "Emission Color" in bsdf.inputs:
            bsdf.inputs["Emission Color"].default_value = rgba
            bsdf.inputs["Emission Strength"].default_value = strength
        else:
            emit = nt.nodes.new("ShaderNodeEmission")
            emit.inputs["Color"].default_value = rgba
            emit.inputs["Strength"].default_value = strength
            add = nt.nodes.new("ShaderNodeAddShader")
            out = next(n for n in nt.nodes if n.type == "OUTPUT_MATERIAL")
            nt.links.new(bsdf.outputs[0], add.inputs[0])
            nt.links.new(emit.outputs[0], add.inputs[1])
            nt.links.new(add.outputs[0], out.inputs["Surface"])
        return mat

    def _open_flap(self, slot_w, slot_h, slot_z, slot_y, front_x, mat):
        """Discharge flap hinged on the slot lip, then swung open.

        ``front_x`` is the real fascia at the hinge, not the pre-wrap plane.
        The hinge sits in that skin so the fin is the front of the opening
        rather than a slab floating in front of it.
        """
        flap_h = slot_h * 0.86
        flap_d = 0.0042
        flap = rounded_box(
            (flap_d, slot_w * 0.96, flap_h),
            location=(0.0, 0.0, 0.0),
            radius=0.0020,
            segments=3,
            name="splitac_flap",
        )
        # Origin at the top-back edge: body in +X (out) and -Z (down).
        flap.location = (flap_d / 2.0, 0.0, -flap_h / 2.0)
        butil.apply_transform(flap, loc=True)
        flap.rotation_euler = (0.0, -self.flap_open, 0.0)
        butil.apply_transform(flap)
        flap.location = (front_x - 0.0003, slot_y, slot_z + slot_h / 2.0 - 0.0018)
        butil.apply_transform(flap, loc=True)
        assign(flap, mat)
        return flap

    def _control_cluster(
        self, housing, y, z, plate_mat, lcd_mat, btn_mat, led_mat, plate_w, plate_h
    ):
        """IR window and status lamps, set into a recess in the fascia."""
        parts = []
        fx = self._fascia_x(housing, y, z)
        plate = self._front_patch(
            plate_w * 0.92, plate_h * 0.88, fx + 0.008, y, z, "splitac_ctrl_plate"
        )
        self._drape_front(plate, housing, offset=0.00008, thickness=0.00032)
        assign(plate, plate_mat)
        parts.append(plate)

        rx, rz = y - plate_w * 0.16, z + plate_h * 0.02
        receiver = self._front_patch(
            plate_w * 0.36,
            plate_h * 0.32,
            fx + 0.009,
            rx,
            rz,
            "splitac_ir_receiver",
            nw=4,
            nh=3,
        )
        self._drape_front(receiver, housing, offset=0.00016, thickness=0.00028)
        assign(receiver, lcd_mat)
        parts.append(receiver)

        for i, (dy, mat, rad) in enumerate(
            ((plate_w * 0.10, led_mat, 0.0015), (plate_w * 0.24, btn_mat, 0.0016))
        ):
            ly, lz = y + dy, z + plate_h * 0.02
            lx = self._fascia_x(housing, ly, lz) + 0.00028
            lamp = cylinder(
                radius=rad,
                depth=0.0007,
                location=(lx, ly, lz),
                rotation=(0.0, math.pi / 2.0, 0.0),
                name=f"splitac_status_lamp_{i}",
            )
            assign(lamp, mat)
            parts.append(lamp)
        return parts

    def _cut_panel_seams(self, housing, front_x, slot_z, slot_h):
        """Shallow horizontal part-lines where the front covers clip together."""
        seam_w = max(0.20, self.width - 2.0 * (self.side_chamfer + 0.04))
        seam_h = 0.0013
        seam_d = 0.0030
        slot_top = slot_z + slot_h / 2.0
        z_upper = min(
            slot_top + 0.038,
            self.height / 2.0 - self.front_fillet - 0.018,
        )
        for i, z in enumerate((z_upper,)):
            cutter = box(
                (seam_d * 2.0, seam_w, seam_h),
                location=(front_x, 0.0, z),
                name=f"splitac_seam_cut_{i}",
            )
            butil.modify_mesh(
                housing,
                "BOOLEAN",
                object=cutter,
                operation="DIFFERENCE",
                solver="EXACT",
            )
            butil.delete(cutter)

    def create_asset(self, **params):
        body_mat = plastic_material(
            f"SplitACBody_{self.factory_seed}",
            self.body_color,
            roughness=uniform(0.24, 0.32),
            sheen_scale=190.0,
        )
        body_bsdf = body_mat.node_tree.nodes.get("Principled BSDF")
        if body_bsdf is not None and "Coat Weight" in body_bsdf.inputs:
            body_bsdf.inputs["Coat Weight"].default_value = 0.16
            body_bsdf.inputs["Coat Roughness"].default_value = 0.22
        trunk_mat = plastic_material(
            f"SplitACTrunk_{self.factory_seed}",
            self.trunk_color,
            roughness=0.42,
        )
        # Recessed cavity: dark from the front, but not an unlit black shader.
        well_mat = solid_material(
            f"SplitACWell_{self.factory_seed}",
            (0.055, 0.062, 0.066),
            roughness=0.62,
        )
        fin_mat = body_mat
        window_mat = solid_material(
            f"SplitACWindow_{self.factory_seed}",
            (0.10, 0.11, 0.12),
            roughness=0.22,
        )
        led_mat = self._emissive(
            f"SplitACLed_{self.factory_seed}",
            self.led_color,
            strength=22.0,
        )
        btn_mat = plastic_material(
            f"SplitACBtn_{self.factory_seed}",
            self.button_color,
            roughness=0.38,
            sheen_scale=90.0,
        )
        plate_mat = plastic_material(
            f"SplitACCtrl_{self.factory_seed}",
            tuple(c * 0.92 for c in self.body_color),
            roughness=0.32,
            sheen_scale=110.0,
        )

        housing_d = self._housing_d()
        slot_depth = self.depth * 0.29
        front_x = housing_d

        left_margin = max(0.042, self.side_chamfer + 0.022)
        right_margin = max(0.070, self.side_chamfer + 0.038)
        slot_w = self.width - left_margin - right_margin
        slot_y = (left_margin - right_margin) / 2.0
        # Outlet geometry. The slot used to be 28% of the height centred at
        # -8%, i.e. straddling the middle of the fascia; on a real head the
        # discharge is a letterbox along the *bottom* edge with the whole upper
        # fascia left clean for the display. Dropped to the lowest position the
        # bottom fillet allows, and made shallower so it reads as a slot.
        slot_h = self.height * 0.165
        slot_z = -self.height / 2.0 + self.front_fillet + self.height * 0.085

        housing = box(
            (housing_d, self.width, self.height),
            location=(housing_d / 2, 0, 0),
            name="splitac_housing",
        )
        self._taper_front(housing)
        self._shape_housing(housing)
        cutter = box(
            (slot_depth * 2.0, slot_w, slot_h),
            location=(front_x, slot_y, slot_z),
            name="splitac_slot_cut",
        )
        butil.modify_mesh(
            housing,
            "BOOLEAN",
            object=cutter,
            operation="DIFFERENCE",
            solver="EXACT",
        )
        butil.delete(cutter)
        self._cut_panel_seams(housing, front_x, slot_z, slot_h)
        top_z = self.height / 2.0
        top_span = max(0.20, self.width - 2.0 * (self.side_chamfer + 0.06))
        top_x0 = self.front_fillet + 0.03
        top_x1 = housing_d - self.front_fillet - 0.03
        well_d = max(0.04, top_x1 - top_x0)
        well_x = 0.5 * (top_x0 + top_x1)
        intake_cut = box(
            (well_d, top_span, 0.006),
            location=(well_x, 0.0, top_z),
            name="splitac_intake_cut",
        )
        butil.modify_mesh(
            housing,
            "BOOLEAN",
            object=intake_cut,
            operation="DIFFERENCE",
            solver="EXACT",
        )
        butil.delete(intake_cut)

        # Control cluster sits on the fascia above the slot, inboard of the wrap.
        plate_w, plate_h = 0.040, 0.015
        ctrl_y = self.width / 2.0 - self.side_chamfer - plate_w * 0.5 - 0.022
        ctrl_z = slot_z + slot_h / 2.0 + plate_h * 0.5 + 0.020

        self._clean_mesh(housing)
        self._shade_by_angle(housing)
        assign(housing, body_mat)
        parts = [housing]

        seam_w = max(0.20, self.width - 2.0 * (self.side_chamfer + 0.04))
        slot_top = slot_z + slot_h / 2.0
        slot_bot = slot_z - slot_h / 2.0
        z_upper = min(slot_top + 0.038, self.height / 2.0 - self.front_fillet - 0.018)
        z_lower = max(slot_bot - 0.022, -self.height / 2.0 + self.front_fillet + 0.016)
        seam_mat = solid_material(
            f"SplitACSeam_{self.factory_seed}",
            tuple(max(0.02, c * 0.55) for c in self.body_color),
            roughness=0.55,
        )
        for i, z in enumerate((z_upper, z_lower)):
            gx = self._fascia_x(housing, 0.0, z)
            gasket = box(
                (0.0010, seam_w * 0.998, 0.0009),
                location=(gx - 0.0006, 0.0, z),
                name=f"splitac_seam_{i}",
            )
            assign(gasket, seam_mat)
            parts.append(gasket)

        slot_fx = self._fascia_x(housing, slot_y, slot_z)
        well = box(
            (0.004, slot_w * 0.998, slot_h * 0.98),
            location=(slot_fx - slot_depth * 0.88, slot_y, slot_z),
            name="splitac_well",
        )
        assign(well, well_mat)
        parts.append(well)
        for y_off, sy in (
            (slot_y - slot_w / 2 + 0.003, 0.004),
            (slot_y + slot_w / 2 - 0.003, 0.004),
        ):
            side_x = self._fascia_x(housing, y_off, slot_z)
            side = box(
                (slot_depth * 0.50, sy, slot_h * 0.94),
                location=(side_x - slot_depth * 0.52, y_off, slot_z),
                name="splitac_slot_side",
            )
            assign(side, well_mat)
            parts.append(side)

        # Deflector vanes, set well back in the throat and stopping short of
        # the opening so the louvre reads as the front surface.
        vane_span = slot_w * 0.94
        vane_t = 0.0032
        n_vanes = self.n_vanes
        pitch = vane_span / max(n_vanes, 1)
        vane_x = slot_fx - slot_depth * 0.62
        for i in range(n_vanes):
            fy = slot_y - vane_span / 2 + (i + 0.5) * pitch
            vane = box(
                (slot_depth * 0.22, vane_t, slot_h * 0.70),
                location=(vane_x, fy, slot_z),
                name=f"splitac_vane_{i}",
            )
            assign(vane, fin_mat)
            parts.append(vane)

        hinge_z = slot_z + slot_h / 2.0
        slot_lip_x = min(
            self._fascia_x(housing, y, hinge_z)
            for y in (slot_y, slot_y - slot_w * 0.45, slot_y + slot_w * 0.45)
        )
        parts.append(
            self._open_flap(slot_w, slot_h, slot_z, slot_y, slot_lip_x, body_mat)
        )

        parts.extend(
            self._control_cluster(
                housing,
                ctrl_y,
                ctrl_z,
                plate_mat,
                window_mat,
                btn_mat,
                led_mat,
                plate_w,
                plate_h,
            )
        )

        # Same random generate_text() badge as the oven/fridge, scaled down
        # for the small fascia and draped on the real front skin.
        brand_z = self.height * 0.12
        brand_x = self._fascia_x(housing, 0.0, brand_z)
        brand_mat = disable_shadow_rays(
            plastic_material(
                f"SplitACBrand_{self.factory_seed}",
                (0.22, 0.22, 0.23),
                roughness=0.42,
            )
        )
        brand = brand_lettering(
            self.brand_name,
            size=min(0.016, self.height * 0.052),
            location=(brand_x + 0.008, 0.0, brand_z),
            extrude=0.00022,
            name="splitac_brand",
        )
        self._seat_text(brand, housing, offset=0.00008)
        assign(brand, brand_mat)
        parts.append(brand)

        # Top intake slats sit in the well, below the lid surface.
        slat_t = 0.0024
        n_top = self.n_top_intake
        gap = well_d / max(n_top, 1)
        for i in range(n_top):
            x = top_x0 + (i + 0.5) * gap
            slat = box(
                (slat_t, top_span * 0.96, 0.0024),
                location=(x, 0.0, top_z - 0.003),
                name=f"splitac_top_intake_{i}",
            )
            assign(slat, body_mat)
            parts.append(slat)

        if self.has_trunk:
            y_face = self.trunk_side * (self.width / 2)
            y_c = y_face + self.trunk_side * (self.trunk_len / 2)
            trunk = box(
                (self.trunk_d, self.trunk_len, self.trunk_h),
                location=(self.trunk_d / 2, y_c, -self.height * 0.08),
                name="splitac_trunk",
            )
            assign(trunk, trunk_mat)
            butil.modify_mesh(trunk, "BEVEL", width=0.004, segments=2)
            parts.append(trunk)
            rise = self.trunk_rise
            riser = box(
                (self.trunk_d * 0.92, self.trunk_d * 1.1, rise),
                location=(
                    self.trunk_d / 2,
                    y_face + self.trunk_side * (self.trunk_len - self.trunk_d * 0.55),
                    -self.height * 0.08 + self.trunk_h / 2 + rise / 2,
                ),
                name="splitac_riser",
            )
            assign(riser, trunk_mat)
            parts.append(riser)

        obj = join_objects(parts)
        # The control cluster's rounded boxes and cylinders left 24 zero-area
        # faces with zero-length normals, which shade black. Welding only the
        # housing missed them because they arrive with the smaller parts.
        self._clean_mesh(obj)
        # Everything above is built from the wall plane at x=0; lift the whole
        # head off it in one move so no part can be coincident with the
        # plaster, whatever is added to the assembly later.
        obj.location = (self.wall_gap, 0.0, 0.0)
        butil.apply_transform(obj, loc=True)
        obj.name = f"SplitACFactory({self.factory_seed}).ac"
        return obj
